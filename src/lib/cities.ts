function uniqueSorted(values: string[]) {
  return [...new Set(values.map((value) => value.trim()).filter(Boolean))].sort((a, b) =>
    a.localeCompare(b, "fa"),
  );
}

export function citiesForCountryName(countryFa: string, extraCities: string[] = []) {
  const country = findCountryByNameFa(countryFa);
  const known = country ? (CITIES_BY_COUNTRY[country.code] ?? []) : [];
  return uniqueSorted([...known, ...extraCities]);
}

export function cityOptionsForCountry(
  countryFa: string,
  extraCities: string[] = [],
  currentCity?: string,
) {
  const cities = citiesForCountryName(countryFa, [
    ...extraCities,
    ...(currentCity?.trim() ? [currentCity] : []),
  ]);
  return cities.map((city) => ({
    value: city,
    label: city,
    keywords: city,
  }));
}
